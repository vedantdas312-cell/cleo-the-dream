import { readFile, writeFile } from 'node:fs/promises';
// WebKit file pages do not consistently support module loading. Bundle our two
// dependency-free sources as one classic script without relaxing file isolation.
const directory = new URL('../desktop/NotepadWeb/', import.meta.url);
const book = (await readFile(new URL('book.mjs', directory), 'utf8')).replace(/^export /gm, '');
const canvas = (await readFile(new URL('canvas.mjs', directory), 'utf8')).replace(/^import .*\n/, '');
await writeFile(new URL('renderer.js', directory), `// Generated by scripts/build-notepad.mjs; edit book.mjs/canvas.mjs.\n(() => {\n${book}\n${canvas}\n})();\n`);
